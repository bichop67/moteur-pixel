ETAPES = {"cloche": "verset", "beurk": "verset", "calomnie": "ping", "ceux": "ongles", "stop": "tel"}
MODES = {"vrai": "ping", "ongles": "ongles", "efface": "efface", "defend": "defend", "defends": "defend"}


def _norm(m):
    return (m.lower().replace("é", "e").replace("è", "e").replace("ê", "e").replace("ï", "i").replace("î", "i")
            .replace("â", "a"))


def ordre(schema, t, brut, mots, reste):
    """Appelé par explique_0811.ordre pour les clés de CLES. Renvoie True si l'ordre a été pris en compte."""
    k = _norm(mots[0])
    sous = _norm(mots[1]) if len(mots) > 1 else ""
    qui = mots[1].upper() if len(mots) > 1 else "PETIT"

    def dernier(mode):
        return next((it["el"] for it in reversed(schema._visibles(t + 0.01))
                     if isinstance(it["el"], Ghiba) and it["el"].mode == mode), None)

    def u_de(el):
        return t - next(it["t_in"] for it in schema.items if it["el"] is el)

    if k == "ghiba":
        if sous == "stop":
            el = dernier("tel")
            if el is None:
                return True
            el.t["stop"] = u_de(el)
        else:
            schema._ajoute(t, Ghiba(brut, "tel", qui if qui in ("PETIT", "GRAND") else "PETIT"))
        return True
    if k == "chair":
        if sous in ETAPES and ETAPES[sous] != "tel":
            el = dernier(ETAPES[sous])
            if el is None:
                el = Ghiba(brut, ETAPES[sous])
                schema._ajoute(t, el)
            el.t[sous] = u_de(el)
        elif sous in MODES:
            schema._ajoute(t, Ghiba(brut, MODES[sous]))
        else:
            schema._ajoute(t, Ghiba(brut, "verset"))
        return True
    return False


def fin_anim(t, mots):
    """Fin de l'animation d'un ordre (pour que le plan de schéma dure assez) ; None = rien à attendre."""
    k = _norm(mots[0])
    sous = _norm(mots[1]) if len(mots) > 1 else ""
    if k == "ghiba":
        return t + (0.8 if sous == "stop" else 1.6)
    if k == "chair":
        return t + {"": 1.2, "cloche": 1.0, "beurk": 0.9, "vrai": 1.6, "calomnie": 0.5, "ongles": 1.4, "ceux": 1.6,
                    "efface": 1.0, "defend": 2.6, "defends": 2.6}.get(sous, 0.8)
    return None
