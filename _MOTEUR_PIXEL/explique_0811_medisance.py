def _emoji(c, x, y, nom):
    """Pose un émoji pixel en (x, y) (coin haut-gauche, pixels du dessin), liseré sombre d'un pixel."""
    rows = _EMO[nom]
    tout_ = np.zeros((c.h, c.w), bool)
    for j, row in enumerate(rows):
        for i, ch in enumerate(row):
            X, Y = x + 1 + i, y + j
            if ch != "." and 0 <= X < c.w and 0 <= Y < c.h:
                tout_[Y, X] = True
    c.outline(tout_, (28, 22, 24))
    for j, row in enumerate(rows):
        for i, ch in enumerate(row):
            if ch != ".":
                c.px(x + 1 + i, y + j, _EMO_COL[ch])


def _segs(ligne):
    """« LE NOUVEAU PUE §V » → [("t", "LE NOUVEAU PUE "), ("e", "V")]."""
    out = []
    for p in re.split(r"(§[A-Z])", ligne):
        if not p:
            continue
        out.append(("e", p[1]) if p.startswith("§") else ("t", p))
    return out


def _larg(ligne, size=9, font=TAHOMA):
    f = ImageFont.truetype(font, size)
    return sum(EMO_W if k == "e" else int(math.ceil(f.getlength(v))) for k, v in _segs(ligne))


def _ecrit(c, x, y, ligne, col, size=9, font=TAHOMA):
    """Écrit une ligne (texte pixel + émojis) à partir de (x, y) ; renvoie la largeur."""
    f = ImageFont.truetype(font, size)
    x0 = x
    for k, v in _segs(ligne):
        if k == "e":
            _emoji(c, int(x), int(y), v)
            x += EMO_W
        else:
            c.text((int(x), int(y)), v, col, size=size, font=font)
            x += int(math.ceil(f.getlength(v)))
    return x - x0


# ---------------------------------------------------------------- textes à l'écran
def _haut(im):
    bb = im.getbbox()
    return im.crop(bb) if bb else im


def _mix(segs, size):
    """Une ligne en plusieurs couleurs : [(texte, couleur), …] (style des étiquettes du moteur)."""
    ims = [_haut(_titre(t, c, size)) for t, c in segs]
    gap = int(size * 0.34)
    W = sum(i.width for i in ims) + gap * (len(ims) - 1)
    H = max(i.height for i in ims)
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    x = 0
    for i in ims:
        out.alpha_composite(i, (x, H - i.height))
        x += i.width + gap
    return out


def _bloc(lignes, size, inter=10):
    """Bloc centré de lignes : chaque ligne = (texte, couleur) ou liste [(texte, couleur), …] (plusieurs couleurs)."""
    ims = []
    for l_ in lignes:
        if isinstance(l_, list):
            ims.append(_mix(l_, size))
        else:
            ims.append(_haut(_titre(l_[0], l_[1], size)))
    W = max(i.width for i in ims)
    H = sum(i.height for i in ims) + inter * (len(ims) - 1)
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    y = 0
    for i in ims:
        out.alpha_composite(i, (int((W - i.width) / 2), y))
        y += i.height + inter
    return out


def _lueur(w, h, col, flou):
    lay = Image.new("RGBA", (int(w + 4 * flou), int(h + 4 * flou)), (0, 0, 0, 0))
    ImageDraw.Draw(lay).ellipse([2 * flou, 2 * flou, 2 * flou + w, 2 * flou + h], fill=(*col, 255))
    return lay.filter(ImageFilter.GaussianBlur(flou))


def _colle(im, sp, cx, cy, a=1.0):
    if a > 0.01:
        im.alpha_composite(_fade(sp, min(1.0, a)), (int(cx - sp.width / 2), int(cy - sp.height / 2)))


def _seuils(w, h, k, graine):
    """Seuils de dissolution (un par pixel du dessin), un peu de gauche à droite : la bulle se défait en poussière."""
    rng = np.random.default_rng(graine)
    thr = rng.random((h // k + 1, w // k + 1))
    thr = 0.7 * thr + 0.3 * np.linspace(0, 1, thr.shape[1])[None, :]
    return np.kron(thr, np.ones((k, k)))[:h, :w]


